#!/usr/bin/env node
// src/network/payments-api/payments-api.json -> src/network/payments-api/payments-api-paths.ts
//
// The list of path templates the Payments API's specification publishes, as a module. The
// payments proxy route needs that list at runtime to tell a path the service serves from one it
// does not, and importing the specification itself to get it would put 130 KB of JSON in the
// server bundle for seventy strings.
//
// A copy of scripts/generate-api-paths.mjs rather than a shared, parameterised generator: that
// one hard-codes both the types module it imports and the name of the constant it exports, and
// the API's generation path is left byte-for-byte unchanged by this change.
//
// It runs beside openapi-typescript in scripts/payments-api-build.sh, so one regeneration
// produces the types and this list together and a new payments endpoint never needs a second,
// manual edit to become reachable. The generated module states `satisfies readonly (keyof
// paths)[]`, which is what fails the build if the two ever are regenerated apart.
//
// Templates are emitted sorted rather than in specification order: the order the backend happens
// to declare its paths in is not something this repository should take a diff for.
//
// Usage:
//   node scripts/generate-payments-api-paths.mjs
//   node scripts/generate-payments-api-paths.mjs --input src/network/payments-api/payments-api.json --output src/network/payments-api/payments-api-paths.ts

import { readFileSync, writeFileSync } from 'node:fs';
import { relative } from 'node:path';

import { format, resolveConfig } from 'prettier';

const args = {};
for (let i = 2; i < process.argv.length; i += 2) {
  args[process.argv[i].replace(/^--/, '')] = process.argv[i + 1];
}
const INPUT = args.input ?? 'src/network/payments-api/payments-api.json';
const OUTPUT = args.output ?? 'src/network/payments-api/payments-api-paths.ts';

const { paths } = JSON.parse(readFileSync(INPUT, 'utf8'));
const templates = Object.keys(paths ?? {}).sort();

if (templates.length === 0) {
  console.error(`${INPUT} declares no paths — refusing to write an empty allow-list.`);
  process.exit(1);
}

const source = `/**
 * This file was auto-generated by scripts/generate-payments-api-paths.mjs.
 * Do not make direct changes to the file.
 */

import type { paths } from './payments-api';

/**
 * Every path template the Payments API publishes. The payments proxy route compiles these into
 * matchers and refuses anything they do not cover, so this is the list a path is checked
 * against before it can be reached through this application's server.
 */
export const PAYMENTS_API_PATH_TEMPLATES = [
${templates.map((template) => `  '${template}',`).join('\n')}
] as const satisfies readonly (keyof paths)[];
`;

writeFileSync(OUTPUT, await format(source, { ...(await resolveConfig(OUTPUT)), filepath: OUTPUT }));

console.log(`${relative(process.cwd(), OUTPUT)}  ${templates.length} path templates`);
