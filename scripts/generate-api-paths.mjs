#!/usr/bin/env node
// src/network/api/api.json -> src/network/api/api-paths.ts
//
// The list of path templates the specification publishes, as a module. The proxy route needs
// that list at runtime to tell a path the API serves from one it does not, and importing the
// specification itself to get it would put 173 KB of JSON in the server bundle for forty-odd
// strings.
//
// It runs beside openapi-typescript in scripts/api-build.sh, so one regeneration produces the
// types and this list together and a new backend endpoint never needs a second, manual edit to
// become reachable. The generated module states `satisfies readonly (keyof paths)[]`, which is
// what fails the build if the two ever are regenerated apart.
//
// Templates are emitted sorted rather than in specification order: the order the backend happens
// to declare its paths in is not something this repository should take a diff for.
//
// Usage:
//   node scripts/generate-api-paths.mjs
//   node scripts/generate-api-paths.mjs --input src/network/api/api.json --output src/network/api/api-paths.ts

import { readFileSync, writeFileSync } from 'node:fs';
import { relative } from 'node:path';

import { format, resolveConfig } from 'prettier';

const args = {};
for (let i = 2; i < process.argv.length; i += 2) {
  args[process.argv[i].replace(/^--/, '')] = process.argv[i + 1];
}
const INPUT = args.input ?? 'src/network/api/api.json';
const OUTPUT = args.output ?? 'src/network/api/api-paths.ts';

const { paths } = JSON.parse(readFileSync(INPUT, 'utf8'));
const templates = Object.keys(paths ?? {}).sort();

if (templates.length === 0) {
  console.error(`${INPUT} declares no paths — refusing to write an empty allow-list.`);
  process.exit(1);
}

const source = `/**
 * This file was auto-generated by scripts/generate-api-paths.mjs.
 * Do not make direct changes to the file.
 */

import type { paths } from './api';

/**
 * Every path template the API publishes. The proxy route compiles these into
 * matchers and refuses anything they do not cover, so this is the list that
 * decides what a browser can reach through this application's server.
 */
export const API_PATH_TEMPLATES = [
${templates.map((template) => `  '${template}',`).join('\n')}
] as const satisfies readonly (keyof paths)[];
`;

writeFileSync(OUTPUT, await format(source, { ...(await resolveConfig(OUTPUT)), filepath: OUTPUT }));

console.log(`${relative(process.cwd(), OUTPUT)}  ${templates.length} path templates`);
